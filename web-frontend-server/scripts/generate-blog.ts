import { mkdirSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { posts } from '../src/features/blog/data/posts.ts'
import type { BlogPost } from '../src/features/blog/types.ts'

const escape = (value: string) =>
  value.replace(
    /[&<>"']/g,
    (char) =>
      ({
        '&': '&amp;',
        '<': '&lt;',
        '>': '&gt;',
        '"': '&quot;',
        "'": '&#39;',
      })[char]!,
  )

const icon = (name: 'clock' | 'arrow' | 'back' | 'search' | 'heart' | 'cloud') => {
  const paths = {
    clock: '<circle cx="12" cy="12" r="9"/><path d="M12 7v5l3 2"/>',
    arrow: '<path d="M5 12h14m-6-6 6 6-6 6"/>',
    back: '<path d="M19 12H5m6-6-6 6 6 6"/>',
    search: '<circle cx="10.5" cy="10.5" r="6.5"/><path d="m16 16 5 5"/>',
    heart:
      '<path d="M20.8 4.6a5.5 5.5 0 0 0-7.8 0L12 5.7l-1.1-1.1a5.5 5.5 0 0 0-7.8 7.8L12 21l8.8-8.6a5.5 5.5 0 0 0 0-7.8Z"/>',
    cloud: '<path d="M7 18h11a4 4 0 0 0 0-8 6 6 0 0 0-11.6-1A4.5 4.5 0 0 0 7 18Z"/>',
  }
  return `<svg class="blog-icon" width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.7" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${paths[name]}</svg>`
}

const brand = `<a href="/" class="brand" aria-label="MiniHome — Trang chủ"><span class="brand-symbol"><img src="/minihome.svg" alt="" class="brand-icon" /></span><span>mini<span class="brand-home font-normal">home</span><small>by MyMiniCloud</small></span></a>`
const navigation = `<a href="/" class="nav-link">Trang chủ</a><a href="/rooms" class="nav-link">Tìm phòng</a><a href="/blog/" class="nav-link active" aria-current="location">Góc sinh viên</a><a href="/students" class="nav-link">Sinh viên</a>`

function card(post: BlogPost) {
  return `<article class="blog-card group ${post.id === 'ngan-sach-sinh-vien' ? 'blog-card-featured' : ''}" data-category="${escape(post.category)}">
    <a href="/blog/${post.htmlFile}" class="blog-card-image block overflow-hidden"><img src="${escape(post.imageUrl)}" alt="${escape(post.title)}" width="800" height="500" loading="lazy" class="aspect-[1.6] w-full object-cover transition duration-200 group-hover:scale-[1.03]" /></a>
    <div class="blog-card-body">
      <div class="blog-card-meta flex items-center justify-between text-xs"><span class="font-semibold text-brand">${escape(post.category)}</span><span class="text-muted">${icon('clock')} ${post.readTime} phút đọc</span></div>
      <h3 class="my-3 text-xl font-semibold leading-snug"><a href="/blog/${post.htmlFile}" class="hover:text-brand">${escape(post.title)}</a></h3>
      <p class="mb-4 text-sm leading-relaxed text-muted">${escape(post.excerpt)}</p>
      <a href="/blog/${post.htmlFile}" class="inline-flex items-center gap-2 text-sm font-semibold text-navy">Đọc bài viết ${icon('arrow')}</a>
    </div>
  </article>`
}

