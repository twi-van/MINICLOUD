#!/bin/bash
# Đề mở rộng: database studentdb, tách khỏi minicloud mà app đang dùng.
set -euo pipefail

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname postgres <<'SQL'
SELECT 'CREATE DATABASE studentdb'
WHERE NOT EXISTS (SELECT FROM pg_database WHERE datname = 'studentdb')\gexec
SQL

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname studentdb <<'SQL'
CREATE TABLE IF NOT EXISTS students (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id VARCHAR(10) UNIQUE,
  fullname VARCHAR(100) NOT NULL,
  dob DATE,
  major VARCHAR(50)
);

