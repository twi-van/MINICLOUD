function listing() {
  return document(
    'Góc nhỏ sinh viên',
    'Những câu chuyện và kinh nghiệm nhỏ, cùng bạn trên hành trình tự lập.',
    `
    <div class="page-container blog-page min-h-150 pb-18">
      <div class="page-intro text-center"><span class="eyebrow">GÓC NHỎ SINH VIÊN</span><h1>Ở hay hơn, <span>sống vui hơn.</span></h1><p>Những câu chuyện và kinh nghiệm nhỏ, cùng bạn trên hành trình tự lập.</p></div>
      <div class="blog-toolbar mb-7 flex flex-wrap items-center justify-between gap-4" data-blog-tools hidden>
        <div class="flex flex-wrap gap-2" role="group" aria-label="Lọc chủ đề">
          ${['Tất cả', ...new Set(posts.map((post) => post.category))].map((category) => `<button type="button" class="blog-button" data-filter="${escape(category)}" aria-pressed="${category === 'Tất cả'}">${escape(category)}</button>`).join('\n')}
        </div>
        <label class="blog-search">${icon('search')}<input type="search" aria-label="Tìm bài viết" placeholder="Tìm một bài viết…" /></label>
      </div>
      <div class="blog-editorial-grid" data-blog-grid>${posts.map(card).join('\n')}</div>
      <p class="blog-empty" role="status" data-blog-empty hidden>Chưa tìm thấy bài viết phù hợp.</p>
      <p class="sr-only" role="status" data-blog-count></p>
    </div>`,
  )
}

function article(post: BlogPost) {
  const date = new Intl.DateTimeFormat('vi-VN', { timeZone: 'Asia/Ho_Chi_Minh' }).format(
    new Date(`${post.date}T12:00:00+07:00`),
  )
  return document(
    post.title,
    post.excerpt,
    `
    <div class="page-container pb-16 pt-8">
      <nav class="blog-breadcrumb" aria-label="Đường dẫn"><a href="/">Trang chủ</a><span aria-hidden="true">/</span><a href="/blog/">Blog</a><span aria-hidden="true">/</span><span>${escape(post.category)}</span></nav>
      <article class="blog-article mx-auto max-w-200 py-10">
        <span class="eyebrow">${escape(post.category)}</span>
        <h1 class="mb-5 mt-4 text-3xl font-semibold leading-tight md:text-[42px]">${escape(post.title)}</h1>
        <div class="mb-7 flex flex-wrap items-center gap-5 text-sm text-muted"><span>MiniHome Editorial</span><time datetime="${post.date}">${date}</time><span>${icon('clock')} ${post.readTime} phút đọc</span></div>
        <img src="${escape(post.imageUrl)}" alt="${escape(post.title)}" width="1200" height="667" fetchpriority="high" class="aspect-[1.8] w-full rounded-2xl object-cover" />
        <p class="my-8 text-lg leading-8 text-muted">${escape(post.excerpt)}</p>
        ${post.sections
          .map(
            (section) =>
              `<section class="my-8"><h2 class="mb-4 text-2xl font-semibold">${escape(section.title)}</h2>${section.content
                .split('\n\n')
                .map(
                  (paragraph) =>
                    `<p class="mb-4 text-[16px] leading-8 text-muted">${escape(paragraph)}</p>`,
                )
                .join('\n')}</section>`,
          )
          .join('\n')}
        <div class="flex flex-wrap gap-5"><a href="/blog/" class="text-link">${icon('back')} Về góc nhỏ sinh viên</a><a href="/" class="text-link">Về trang chủ ${icon('arrow')}</a></div>
      </article>
      <div class="border-t border-line pt-10"><h2 class="mb-7 text-2xl font-semibold">Thêm một chút cảm hứng</h2><div class="grid gap-8 md:grid-cols-2">${posts
        .filter((item) => item.id !== post.id)
        .map(card)
        .join('\n')}</div></div>
    </div>`,
  )
}

export function generateBlog() {
  const directory = fileURLToPath(new URL('../blog/', import.meta.url))
  mkdirSync(directory, { recursive: true })
  writeFileSync(`${directory}/index.html`, listing())
  for (const post of posts) writeFileSync(`${directory}/${post.htmlFile}`, article(post))
}
